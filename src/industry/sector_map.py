"""证监会行业(baostock industry) → 中证一级行业 的映射。

中证一级行业指数(baostock 可取，市值加权、官方)只有 10 个大类，用于宏观行业强弱；
更细的证监会行业(86 个)由 IndustryRanker 自算(中位数)补充粒度。
"""

from __future__ import annotations

import re

# 一级行业指数代码 → 名称。优先用沪深300行业指数(000910-000919，baostock 全可取)，
# 其中 baostock 缺失的医药/金融用中证全指对应指数(000933/000934)补齐，凑齐 10 个大类。
CSI_SECTORS: dict[str, str] = {
    "000910": "能源",
    "000911": "原材料",
    "000912": "工业",
    "000913": "可选消费",
    "000914": "主要消费",
    "000933": "医药卫生",
    "000934": "金融地产",
    "000917": "信息技术",
    "000918": "电信业务",
    "000919": "公用事业",
}
NAME_TO_CODE = {name: code for code, name in CSI_SECTORS.items()}

# 证监会制造业(C)二级 → 中证一级
_C_SUBCODE = {
    "13": "主要消费", "14": "主要消费", "15": "主要消费",  # 食品/酒饮料
    "17": "可选消费", "18": "可选消费", "19": "可选消费",  # 纺织/服装/皮革
    "20": "工业", "21": "可选消费", "22": "原材料", "23": "工业",  # 木材/家具/造纸/印刷
    "25": "能源", "26": "原材料", "27": "医药卫生", "28": "原材料", "29": "原材料",  # 石油加工/化学/医药/化纤/橡胶塑料
    "30": "原材料", "31": "原材料", "32": "原材料", "33": "工业",  # 非金属/黑色/有色/金属制品
    "34": "工业", "35": "工业", "36": "可选消费", "37": "工业", "38": "工业",  # 通用/专用/汽车/铁路船舶/电气机械
    "39": "信息技术", "40": "信息技术", "41": "工业", "42": "公用事业", "43": "工业",  # 计算机电子/仪表/其他/废弃/修理
}
# 证监会门类(首字母) → 中证一级
_LETTER = {
    "A": "主要消费", "B": "能源", "D": "公用事业", "E": "工业", "F": "可选消费",
    "G": "工业", "H": "可选消费", "I": "信息技术", "J": "金融地产", "K": "金融地产",
    "L": "工业", "M": "信息技术", "N": "公用事业", "P": "可选消费", "Q": "医药卫生",
    "R": "可选消费", "S": "工业",
}


def csi_sector(industry_l1: str | None) -> str | None:
    """把证监会行业名(形如 'C39计算机...'、'J66货币金融服务')映射到中证一级行业名。"""
    if not industry_l1:
        return None
    text = str(industry_l1).strip()
    match = re.match(r"([A-Z])(\d{2})?", text)
    if not match:
        return None
    letter, sub = match.group(1), match.group(2)
    if letter == "C":
        if sub and sub in _C_SUBCODE:
            return _C_SUBCODE[sub]
        return "工业"  # 制造业默认归工业
    if letter == "I" and sub == "63":
        return "电信业务"
    return _LETTER.get(letter)
